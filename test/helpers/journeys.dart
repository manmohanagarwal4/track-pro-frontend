ProviderContainer containerOf(WidgetTester tester) =>
    ProviderScope.containerOf(tester.element(find.byType(TrackProApp)));

Future<void> _back(WidgetTester tester) async {
  await tester.pageBack();
  await pumpFor(tester, const Duration(milliseconds: 700));
}

/// Spec §57: splash → onboarding → demo login → dashboard → map → Truck 21 →
/// live movement → details → history → trips → geofence → enter/exit alert →
/// open alert → mark as read.
Future<void> mainJourney(WidgetTester tester) async {
  await pumpApp(tester, onboarded: false);
  expect(find.text('Track anything that matters'), findsOneWidget);
  await tapAndWait(tester, find.text('Skip'));
  await tapAndWait(tester, find.byKey(const Key('login-demo')), wait: const Duration(seconds: 2));
  expect(find.text('Total Devices'), findsOneWidget);
  final c = containerOf(tester);

  // Map
  await tapAndWait(tester, find.text('Map').last, wait: const Duration(seconds: 1));
  expect(find.textContaining('Search'), findsWidgets);

  // Select Truck 21 via Fleet search
  await tapAndWait(tester, find.text('Fleet').last);
  await tester.enterText(find.byKey(const Key('fleet-search')), 'Truck 21');
  await pumpFor(tester, const Duration(milliseconds: 500));
  await tapAndWait(tester, find.descendant(of: find.byType(DeviceCard), matching: find.text('Truck 21')).first,
      wait: const Duration(seconds: 1));
  expect(find.text('Current Location'), findsOneWidget);

  // Live location: the marker's position changes as the simulation runs.
  final before = c.read(deviceViewProvider('TRUCK-001'))!.position!;
  await pumpFor(tester, const Duration(seconds: 6), step: const Duration(milliseconds: 250));
  final after = c.read(deviceViewProvider('TRUCK-001'))!.position!;
  expect(before == after, isFalse, reason: 'Truck 21 should have moved');

  // Telemetry
  await tester.scrollUntilVisible(find.text('Ignition'), 300, scrollable: find.byType(Scrollable).first);
  expect(find.text('Satellites'), findsOneWidget);
  await tester.scrollUntilVisible(find.byKey(const Key('action-History')), -300, scrollable: find.byType(Scrollable).first);

  // History
  await tapAndWait(tester, find.byKey(const Key('action-History')), wait: const Duration(seconds: 1));
  expect(find.textContaining('History'), findsWidgets);
  await tapAndWait(tester, find.widgetWithText(ChoiceChip, 'Last 7 Days'), wait: const Duration(seconds: 1));
  await tester.scrollUntilVisible(find.text('Average Speed'), 300, scrollable: find.byType(Scrollable).last);
  expect(find.text('Maximum Speed'), findsOneWidget);
  await _back(tester);

  // Trips
  await tapAndWait(tester, find.byKey(const Key('action-Trips')), wait: const Duration(seconds: 1));
  expect(find.textContaining('trips ·'), findsOneWidget);
  await tapAndWait(tester, find.textContaining(' → ').first, wait: const Duration(seconds: 1));
  await tester.scrollUntilVisible(find.text('Stops'), 300, scrollable: find.byType(Scrollable).first);
  expect(find.text('Distance'), findsOneWidget);
  await _back(tester);
  await _back(tester);

  // Create a geofence around the moving truck; it will soon exit it.
  await tapAndWait(tester, find.byKey(const Key('action-Geofence')), wait: const Duration(seconds: 1));
  expect(find.text('Create Geofence'), findsOneWidget);
  await tester.enterText(find.byKey(const Key('geofence-name')), 'Truck test zone');
  await pumpFor(tester, const Duration(milliseconds: 300));
  await tapAndWait(tester, find.byKey(const Key('geofence-save')), wait: const Duration(seconds: 1));
  expect(c.read(geofencesProvider).value!.any((g) => g.name == 'Truck test zone'), isTrue);

  // Device exits the fence → alert generated by the rules engine.
  c.read(settingsProvider.notifier).update((s) => s.copyWith(simulationSpeed: 5));
  bool hasExit() => c
      .read(alertsProvider)
      .value!
      .any((a) => a.type == AlertType.geofenceExit && a.message.contains('Truck test zone'));
  for (var i = 0; i < 120 && !hasExit(); i++) {
    await pumpFor(tester, const Duration(seconds: 1), step: const Duration(milliseconds: 250));
  }
  expect(hasExit(), isTrue, reason: 'geofence exit alert should be generated from movement');

  // Open alert → mark as read. (Dismiss the in-app banner that covers the app bar.)
  c.read(alertBannerProvider.notifier).dismiss();
  await pumpFor(tester, const Duration(milliseconds: 600));
  await tester.pageBack();
  await pumpFor(tester, const Duration(milliseconds: 700));
  await tapAndWait(tester, find.text('Alerts').last);
  final alert = c.read(alertsProvider).value!.firstWhere((a) => a.message.contains('Truck test zone'));
  expect(alert.read, isFalse);
  await tapAndWait(tester, find.text(alert.message).first, wait: const Duration(seconds: 1));
  expect(c.read(alertsProvider).value!.firstWhere((a) => a.id == alert.id).read, isTrue);
  await disposeApp(tester);
}

/// Spec §58: personal pet journey.
Future<void> petJourney(WidgetTester tester) async {
  await pumpApp(tester, signedInAs: AccountType.personal);
  final c = containerOf(tester);
  await tester.scrollUntilVisible(find.text('Add tracker'), 300, scrollable: find.byType(Scrollable).first);
  await tapAndWait(tester, find.text('Add tracker').first);
  await tester.enterText(find.byKey(const Key('add-device-id')), 'PET-777');
  await tapAndWait(tester, find.byKey(const Key('add-device-continue')));
  await tapAndWait(tester, find.byKey(const Key('asset-type-pet')));
  await tester.enterText(find.byKey(const Key('add-device-name')), 'Rocky');
  await tapAndWait(tester, find.byKey(const Key('add-device-submit')), wait: const Duration(seconds: 1));
  expect(find.text('Device Added Successfully'), findsOneWidget);
  await tapAndWait(tester, find.byKey(const Key('add-device-view')), wait: const Duration(seconds: 1));
  expect(find.text('Rocky'), findsWidgets);

  // Live map focused on the pet, movement simulation.
  await tapAndWait(tester, find.byKey(const Key('action-Track Live')), wait: const Duration(seconds: 1));
  expect(find.byKey(const Key('map-follow')), findsOneWidget);
  final p0 = c.read(deviceViewProvider('PET-777'))!.position!;
  await pumpFor(tester, const Duration(seconds: 5), step: const Duration(milliseconds: 250));
  expect(c.read(deviceViewProvider('PET-777'))!.position == p0, isFalse);

  // Bruno leaves the Home Safe Zone → alert.
  c.read(settingsProvider.notifier).update((s) => s.copyWith(simulationSpeed: 10));
  bool exited() => c
      .read(alertsProvider)
      .value!
      .any((a) => a.type == AlertType.geofenceExit && a.deviceId == 'PET-001' && !a.id.startsWith('seed'));
  for (var i = 0; i < 150 && !exited(); i++) {
    await pumpFor(tester, const Duration(seconds: 1), step: const Duration(milliseconds: 500));
  }
  expect(exited(), isTrue, reason: 'Bruno should exit the Home Safe Zone');
  await disposeApp(tester);
}

/// Spec §59: commercial journey.
Future<void> commercialJourney(WidgetTester tester) async {
  await pumpApp(tester, signedInAs: AccountType.business);
  final c = containerOf(tester);
  expect(find.text('Fleet utilisation'), findsOneWidget);
  await tapAndWait(tester, find.text('Fleet').last);
  expect(find.text('Fleet Overview'), findsOneWidget);
  await tester.enterText(find.byKey(const Key('fleet-search')), 'Truck 21');
  await pumpFor(tester, const Duration(milliseconds: 500));
  await tapAndWait(tester, find.descendant(of: find.byType(DeviceCard), matching: find.text('Truck 21')).first,
      wait: const Duration(seconds: 1));

  // Driver
  await tester.scrollUntilVisible(find.text('Amit Kumar'), 300, scrollable: find.byType(Scrollable).first);
  expect(find.text('Amit Kumar'), findsOneWidget);
  await tester.scrollUntilVisible(find.byKey(const Key('action-Track Live')), -300,
      scrollable: find.byType(Scrollable).first);

  // Live tracking
  await tapAndWait(tester, find.byKey(const Key('action-Track Live')), wait: const Duration(seconds: 1));
  expect(find.byKey(const Key('map-details')), findsOneWidget);

  // Trip history (Trips tab)
  await tapAndWait(tester, find.text('Trips').last, wait: const Duration(seconds: 1));
  expect(find.textContaining('trips ·'), findsOneWidget);

  // Overspeed alert
  await tapAndWait(tester, find.text('Alerts').last);
  expect(find.text('Truck 21 exceeded 80 km/h.'), findsOneWidget);

  // Geofences
  await tapAndWait(tester, find.text('More').last);
  await tapAndWait(tester, find.text('Geofences'));
  expect(find.text('Ghaziabad Warehouse'), findsOneWidget);
  await _back(tester);

  // Driver assignment: assign an off-duty driver to Truck 21.
  await tapAndWait(tester, find.text('Drivers'));
  final offDuty = c.read(driversProvider).value!.firstWhere((d) => d.assetId == null);
  await tester.scrollUntilVisible(find.text(offDuty.name), 300, scrollable: find.byType(Scrollable).last);
  await tapAndWait(tester, find.text(offDuty.name));
  await tapAndWait(tester, find.byKey(const Key('driver-assign')));
  await tester.enterText(find.byType(TextField).last, 'Truck 21');
  await pumpFor(tester, const Duration(milliseconds: 400));
  await tapAndWait(tester, find.byKey(const Key('assign-TRUCK-001')), wait: const Duration(seconds: 1));
  final drivers = c.read(driversProvider).value!;
  expect(drivers.firstWhere((d) => d.id == offDuty.id).assetId, 'ast-TRUCK-001');
  expect(drivers.where((d) => d.assetId == 'ast-TRUCK-001').length, 1, reason: 'previous driver unassigned');
  expect(c.read(deviceViewProvider('TRUCK-001'))!.driver!.id, offDuty.id);
  await disposeApp(tester);
}
